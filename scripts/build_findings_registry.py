#!/usr/bin/env python3
"""Build docs/reviews/FINDINGS.md from docs/reviews/failure-classes/*.json.

Stdlib only. One JSON file per proven finding; the aggregate is GENERATED, never
hand-edited. `--check` exits 1 if a file is invalid or the aggregate is stale.
Every key a finding uses is rendered (unknown keys go under "Additional
fields"), so a field can never be silently dropped from the aggregate.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DIR = ROOT / "docs" / "reviews" / "failure-classes"
DEFAULT_OUT = ROOT / "docs" / "reviews" / "FINDINGS.md"

REQUIRED = ("slug", "title", "class_symptom", "mechanism", "first_seen",
            "measurements", "detection", "related")
KNOWN = set(REQUIRED) | {"owner_decision"}
STATUSES = ("guarded", "unguarded")


def validate(data: object, stem: str) -> list[str]:
    errs: list[str] = []
    if not isinstance(data, dict):
        return [f"{stem}: top level must be an object"]
    for key in REQUIRED:
        if key not in data:
            errs.append(f"{stem}: missing required key '{key}'")
    if errs:
        return errs
    if data["slug"] != stem:
        errs.append(f"{stem}: slug '{data['slug']}' must equal the file name")
    for key in ("title", "class_symptom", "mechanism"):
        if not isinstance(data[key], str) or not data[key].strip():
            errs.append(f"{stem}: '{key}' must be a non-empty string")
    fs = data["first_seen"]
    if not (isinstance(fs, dict) and fs.get("date")
            and isinstance(fs.get("evidence"), list) and fs["evidence"]):
        errs.append(f"{stem}: first_seen needs 'date' and a non-empty 'evidence' list")
    if not (isinstance(data["measurements"], list) and data["measurements"]):
        errs.append(f"{stem}: 'measurements' must be a non-empty list (unproven = not a finding)")
    if not isinstance(data["related"], list):
        errs.append(f"{stem}: 'related' must be a list")
    det = data["detection"]
    if not isinstance(det, dict) or det.get("status") not in STATUSES:
        errs.append(f"{stem}: detection.status must be one of {STATUSES}")
    elif det["status"] == "guarded" and not det.get("check"):
        errs.append(f"{stem}: guarded needs detection.check (the named gate/check)")
    elif det["status"] == "unguarded" and not det.get("reason"):
        errs.append(f"{stem}: unguarded needs detection.reason")
    return errs


def _fmt(value: object, indent: int = 0) -> list[str]:
    pad = "  " * indent
    if isinstance(value, dict):
        out: list[str] = []
        for k, v in value.items():
            if isinstance(v, (dict, list)):
                out.append(f"{pad}- **{k}:**")
                out.extend(_fmt(v, indent + 1))
            else:
                out.append(f"{pad}- **{k}:** {v}")
        return out
    if isinstance(value, list):
        out = []
        for v in value:
            if isinstance(v, (dict, list)):
                out.append(f"{pad}-")
                out.extend(_fmt(v, indent + 1))
            else:
                out.append(f"{pad}- {v}")
        return out
    return [f"{pad}- {value}"]


def render_one(d: dict) -> str:
    lines = [f"## {d['title']}", "",
             f"`{d['slug']}` - detection: **{d['detection']['status']}**", "",
             "**Class (symptom):** " + d["class_symptom"], "",
             "**Mechanism:** " + d["mechanism"], "",
             f"**First seen:** {d['first_seen']['date']}"]
    lines += _fmt(d["first_seen"]["evidence"])
    extra_fs = {k: v for k, v in d["first_seen"].items() if k not in ("date", "evidence")}
    if extra_fs:
        lines += _fmt(extra_fs)
    lines += ["", "**Measurements:**"] + _fmt(d["measurements"])
    lines += ["", "**Detection:**"] + _fmt(d["detection"])
    lines += ["", "**Related:**"] + (_fmt(d["related"]) if d["related"] else ["- (none)"])
    if d.get("owner_decision"):
        lines += ["", "**Owner decision:**"] + _fmt(d["owner_decision"])
    extras = {k: v for k, v in d.items() if k not in KNOWN}
    if extras:
        lines += ["", "**Additional fields:**"] + _fmt(extras)
    return "\n".join(lines)


def _anchor(title: str) -> str:
    keep = "".join(c.lower() if c.isalnum() or c in " -" else "" for c in title)
    return keep.strip().replace(" ", "-")


def build(src: Path) -> tuple[str, list[str]]:
    errs: list[str] = []
    items: list[dict] = []
    for f in sorted(src.glob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except ValueError as exc:
            errs.append(f"{f.stem}: invalid JSON ({exc})")
            continue
        e = validate(data, f.stem)
        errs += e
        if not e:
            items.append(data)
    head = ["<!-- GENERATED by scripts/build_findings_registry.py - do not edit by hand. -->",
            "# Findings registry", "",
            "One JSON file per proven finding in `docs/reviews/failure-classes/`. "
            "See `docs/reviews/README.md` to add one.", "",
            "| Finding | Detection | First seen |", "|---|---|---|"]
    for d in items:
        head.append(f"| [{d['title']}](#{_anchor(d['title'])}) | "
                    f"{d['detection']['status']} | {d['first_seen']['date']} |")
    body = "\n\n".join(render_one(d) for d in items)
    return "\n".join(head) + "\n\n" + body + "\n", errs


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if invalid or aggregate is stale")
    ap.add_argument("--dir", type=Path, default=DEFAULT_DIR)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    a = ap.parse_args(argv)
    text, errs = build(a.dir)
    if errs:
        print("\n".join(errs), file=sys.stderr)
        return 1
    if a.check:
        cur = a.out.read_bytes().decode("utf-8") if a.out.exists() else None
        if cur != text:
            print(f"STALE: {a.out} differs from the generated output; run "
                  "`python scripts/build_findings_registry.py`", file=sys.stderr)
            return 1
        print(f"OK: {a.out.name} is current")
        return 0
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_bytes(text.encode("utf-8"))
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

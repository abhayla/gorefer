"""Link Matrix rail (owner rule 2026-11-10, CLAUDE.md §6g).

The published artifact "GoRefer Link Matrix" lists every public link and what it does.
It goes stale silently, so this test pins the public link surface - the routes in
gorefer/urls.py, the posting codes and the language codes - against a snapshot. When
you add, remove or change a link, this test fails until you:

  1. update the Link Matrix artifact (URL in CLAUDE.md §6g), then
  2. regenerate the snapshot:
       UPDATE_LINK_SNAPSHOT=1 python -m pytest tests/test_link_matrix_rail.py -q
     and commit docs/links/public-link-surface.txt in the same PR.

Static (no database): it reads source text only.
"""
import os
import re
from pathlib import Path

from apps.config import preferences as prefkeys
from gorefer.flags import SHARE_CHANNEL_LABELS, SHARE_INTENT_CHANNELS

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "docs" / "links" / "public-link-surface.txt"
MATRIX_URL = "https://claude.ai/artifact/Lky5h29zPXZVa3psft1zoV"


def current_surface() -> str:
    source = (ROOT / "gorefer" / "urls.py").read_text(encoding="utf-8")
    routes = sorted(set(re.findall(r'\bpath\(\s*"([^"]*)"', source)))
    lines = ["# Public link surface. Generated by tests/test_link_matrix_rail.py - do not edit by hand.",
             f"# Every change here must also be made in the GoRefer Link Matrix: {MATRIX_URL}",
             "", "[routes in gorefer/urls.py]"]
    lines += [f"/{route}" for route in routes]
    lines += ["", "[posting codes]", " ".join(sorted(SHARE_CHANNEL_LABELS)),
              "", "[one-tap share channels served]", " ".join(sorted(SHARE_INTENT_CHANNELS)),
              "", "[language codes]", " ".join(sorted(prefkeys.LINK_LANGUAGE_LABELS_DEFAULT)), ""]
    return "\n".join(lines)


def test_link_surface_matches_the_snapshot_the_matrix_was_updated_for():
    surface = current_surface()
    if os.environ.get("UPDATE_LINK_SNAPSHOT") == "1":
        SNAPSHOT.write_text(surface, encoding="utf-8")
    recorded = SNAPSHOT.read_text(encoding="utf-8") if SNAPSHOT.exists() else ""
    assert surface == recorded, (
        "The public link surface changed (a route, a posting code or a language code).\n"
        f"1. Update the GoRefer Link Matrix artifact: {MATRIX_URL}\n"
        "2. Then run: UPDATE_LINK_SNAPSHOT=1 python -m pytest tests/test_link_matrix_rail.py -q\n"
        "   and commit docs/links/public-link-surface.txt (CLAUDE.md §6g)."
    )
